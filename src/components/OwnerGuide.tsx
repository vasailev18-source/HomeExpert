    setStepStates(prev => {
      const current = prev[stepNum] || {
        delivered: false,
        done: false,
        photoDone: false,
        checked: false,
        accepted: false,
        ownerChecks: {},
        photosTaken: {},
        actualCost: null
      };
      
      const updated = { ...current, [prop]: !current[prop] };
      
      // Auto propagation of states
      if (prop === 'accepted' && updated.accepted) {
        updated.delivered = true;
        updated.done = true;
        updated.checked = true;
        updated.photoDone = true;
      }

      return {
        ...prev,
        [stepNum]: updated
      };
    });
